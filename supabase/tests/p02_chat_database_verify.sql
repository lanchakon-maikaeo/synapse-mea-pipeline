begin;
select set_config('test.material_count',(select count(*)::text from core.materials),true);
set local role authenticated;
do $$
declare r jsonb; request uuid:=gen_random_uuid(); args jsonb;
begin
  perform set_config('request.jwt.claim.sub','9bd65a3f-a46d-47b0-a02c-2b27837a382f',true);
  r:=public.vmi_chat_database('discover_database','{}',request);
  assert r->>'status'='forbidden','admission required';
  perform public.vmi_chat_admit(request);
  r:=public.vmi_chat_database('discover_database','{}',request);
  assert r->>'status'='ok' and jsonb_array_length(r->'data')>80,'broad business catalog';
  assert not exists(select 1 from jsonb_array_elements(r->'data') x where x->>'source_id' like 'auth.%' or x->>'source_id'='ops.one_time_worker_triggers'),'no credentials';
  r:=public.vmi_chat_database('query_database','{"source_id":"core.districts","columns":["district_id","district_name_th"],"filters":[{"column":"district_id","operator":"eq","value":"5501"}]}',request);
  assert r->>'status'='ok' and r->'data'->0->>'district_name_th'='นวลจันทร์','district name from live registry';
  r:=public.vmi_chat_database('query_database','{"source_id":"core.materials","metrics":[{"function":"count","column":"*"}],"limit":1}',request);
  assert r->'data'->0->>'count_rows'=current_setting('test.material_count'),'aggregate precedes limit';
  r:=public.vmi_chat_database('query_database','{"source_id":"core.districts","columns":["district_id"],"limit":1}',request);
  assert (r->'scope'->>'truncated')::boolean and jsonb_array_length(r->'data')=1,'bounded paging';
  r:=public.vmi_chat_database('query_database','{"source_id":"core.districts","columns":["district_name_th"],"search":"นวลจันทร์"}',request);
  assert r->>'status'='ok' and jsonb_array_length(r->'data')=1,'Thai search';
  r:=public.vmi_chat_database('query_database','{"source_id":"core.districts","columns":["district_id; drop table core.districts"]}',request);
  assert r->>'status'='invalid_input','column injection';
  r:=public.vmi_chat_database('query_database','{"source_id":"auth.users"}',request);
  assert r->>'status'='forbidden','unregistered source denied';
  r:=public.vmi_chat_database('query_database',jsonb_build_object('source_id','core.districts','filters',jsonb_build_array(jsonb_build_object('column','district_id','operator','eq','value','5501'' OR true --'))),request);
  assert r->>'status'='no_data','filter value is a literal';
  r:=public.vmi_chat_database('query_database','{"source_id":"core.districts","sql":"select 1"}',request);
  assert r->>'status'='invalid_input','raw SQL rejected';
  r:=public.vmi_chat_database('query_database','{"source_id":"core.districts","metrics":[{"function":"pg_sleep","column":"district_id"}]}',request);
  assert r->>'status'='invalid_input','arbitrary function rejected';
  perform set_config('request.jwt.claim.sub','2199851f-76f3-40d7-9574-d57a4fa83c32',true);
  r:=public.vmi_chat_database('discover_database','{}',request);
  assert r->>'status'='forbidden','admission cannot cross actor';
  request:=gen_random_uuid(); perform public.vmi_chat_admit(request);
  r:=public.vmi_chat_database('query_database','{"source_id":"analytics.v_stock_health","columns":["district_id","material_id"]}',request);
  assert r->>'status'='ok' and not exists(select 1 from jsonb_array_elements(r->'data') x where x->>'district_id'<>'5501'),'district isolation';
  r:=public.vmi_chat_database('query_database','{"source_id":"analytics.v_stock_health","filters":[{"column":"district_id","operator":"eq","value":"5502"}]}',request);
  assert r->>'status'='no_data','cross district filters cannot widen scope';
  r:=public.vmi_chat_database('query_database','{"source_id":"core.contracts"}',request);
  assert r->>'status'='forbidden','contract role restriction retained';
  perform set_config('request.jwt.claim.sub','e7fb2f14-bd3c-4e62-937d-5d100373790a',true);
  r:=public.vmi_chat_database('query_database','{"source_id":"core.districts"}',request);
  assert r->>'status'='forbidden','inactive user';
end $$;
rollback;
